// Returns metadata for any word with graceful fallback
export function getWordMeta(word) {
  if (!word) {
    return {
      emoji: "❓",
      desc: "Top Secret: You have no word. Blend in and deduct the civilians' secret word!",
      image: "/bg-cyber.png",
      tags: ["Classified", "Espionage", "Mystery"]
    };
  }

  // Exact match
  if (WORD_METADATA[word]) {
    return WORD_METADATA[word];
  }

  // Case-insensitive match
  const lower = word.toLowerCase();
  for (const [key, val] of Object.entries(WORD_METADATA)) {
    if (key.toLowerCase() === lower) {
      return val;
    }
  }

  // Default fallback for any custom or new words
  return {
    emoji: "💡",
    desc: `Secret Word: "${word}". Craft a clever single-word clue without revealing it!`,
    image: `https://images.unsplash.com/photo-1518770660439-4636190af475?auto=format&fit=crop&w=500&q=80`,
    tags: ["Secret Clue", "Wordplay"]
  };
}
